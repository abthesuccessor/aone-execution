import { mkdir, writeFile } from "node:fs/promises";

const categories = ["Architecture", "Editorial", "Identity", "Illustration", "Objects", "Photography"];
const titles = ["Silent Geometry", "New Rituals", "Soft Assembly", "Light Studies", "Common Ground", "Future Memory", "Open Form", "Material Notes", "Parallel Lines", "Field Record", "Useful Wonder", "After Image"];
const creators = ["Aster Bureau", "Morrow Office", "Studio Nami", "Civic Practice", "Atelier Lune", "North Archive", "Common Era", "Form & Field", "Still Works", "Other Matter"];
const palettes = [["#F1C44B", "#D54D35", "#17243E"], ["#8DC6B2", "#F0E8DA", "#173632"], ["#C8A7E8", "#ED6C4D", "#271D39"], ["#7397D2", "#E6D7BA", "#18304D"], ["#E57F9A", "#F2C14E", "#3A1725"], ["#B8D65C", "#EDE9DB", "#23301D"]];

await mkdir("public/artwork", { recursive: true });
await mkdir("src/data", { recursive: true });
const records = [];
for (let index = 0; index < 120; index += 1) {
  const n = index + 1;
  const id = `frame-${n}`;
  const category = categories[index % categories.length];
  const title = `${titles[index % titles.length]} ${String(Math.floor(index / titles.length) + 1).padStart(2, "0")}`;
  const creator = creators[(index * 7) % creators.length];
  const [a, b, c] = palettes[index % palettes.length];
  const wide = index % 5 === 0;
  const width = wide ? 1200 : 900;
  const height = wide ? 900 : 1125;
  const file = `frame-${String(n).padStart(3, "0")}.svg`;
  const x = 90 + (index * 37) % 340;
  const y = 100 + (index * 29) % 430;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="t d"><title id="t">${title}</title><desc id="d">Original geometric composition in ${a}, ${b}, and ${c}</desc><rect width="100%" height="100%" fill="${c}"/><circle cx="${x + 190}" cy="${y + 120}" r="${130 + index % 80}" fill="${a}"/><rect x="${x}" y="${y + 230}" width="${430 + index % 140}" height="${170 + index % 110}" rx="${index % 2 ? 90 : 0}" fill="${b}"/><path d="M0 ${height - 180} L${width} ${190 + index % 220} V${height}H0Z" fill="${a}" opacity=".72"/><path d="M${width - 310} 0V${height}M0 ${height / 2}H${width}" stroke="${b}" stroke-width="18" opacity=".7"/><text x="64" y="${height - 58}" fill="#fff" font-family="Arial,sans-serif" font-size="26" letter-spacing="8">FRAME / ${String(n).padStart(3, "0")}</text></svg>`;
  await writeFile(`public/artwork/${file}`, svg);
  records.push({ id, title, creator, category, artworkSrc: `/artwork/${file}`, artworkAlt: `Abstract artwork for ${title} by ${creator}`, width, height, accent: a });
}
const source = `import type { GalleryItem } from "../domain/gallery";\n\n// Generated by scripts/generate-fixtures.mjs. Do not hand-edit.\nexport const galleryFixtures = ${JSON.stringify(records, null, 2)} as const satisfies readonly GalleryItem[];\n`;
await writeFile("src/data/fixtures.generated.ts", source);
console.log(`Generated ${records.length} fixture records and SVG artworks.`);
